#!/usr/bin/env bash
# Guided self-hosted installation. Configuration is never evaluated as shell code.
set -euo pipefail
umask 077

root=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
env_file="$root/.env.installation"
configure_only=false
browser_setup=false
while (($#)); do
  case "$1" in
    --browser-setup) browser_setup=true; shift ;;
    --configure-only) configure_only=true; shift ;;
    --env-file)
      [[ $# -ge 2 ]] || { echo 'Missing path after --env-file.' >&2; exit 1; }
      env_file=$2; shift 2 ;;
    --help|-h)
      echo 'Usage: scripts/install.sh [--configure-only] [--browser-setup] [--env-file PATH]'
      echo 'Creates configuration, builds Spool, and waits for Redis/PostgreSQL readiness.'
      echo 'Reruns reuse saved credentials. --configure-only saves and validates without starting services.'
      exit 0 ;;
    *) echo "Unknown option: $1" >&2; exit 1 ;;
  esac
done
env_file="$(cd "$(dirname "$env_file")" && pwd)/$(basename "$env_file")"

fail() { echo "$*" >&2; exit 1; }
command -v docker >/dev/null || fail 'Install Docker with the Compose plugin first.'
docker compose version >/dev/null || fail 'Docker Compose is required (with support for up --wait).'

# Use the saved installation, even when the caller exported development settings.
compose() (
  unset COMPOSE_FILE COMPOSE_PATH_SEPARATOR COMPOSE_PROJECT_NAME COMPOSE_PROFILES
  unset REDIS_URL DATABASE_URL PROMETHEUS_URL POSTGRES_PASSWORD
  unset SPOOL_METRICS_TOKEN SPOOL_MULTI_ORG SPOOL_ORGANIZATION_NAME SPOOL_DATA_KEY SPOOL_SETUP_TOKEN
  unset SPOOL_INSTANCE_NAME SPOOL_SUPPORT_URL SPOOL_METRICS_JOB SPOOL_DEPLOYMENT_MODE
  unset SPOOL_ADDR SPOOL_ENV SPOOL_ADMIN_USER SPOOL_ADMIN_PASSWORD SPOOL_SESSION_KEY
  unset SPOOL_VIEWER_USER SPOOL_VIEWER_PASSWORD SPOOL_READ_ONLY SPOOL_SECURE_COOKIE SPOOL_HOST_PORT
  cd "$root"
  docker compose --env-file "$env_file" "$@"
)

ask() {
  local label=$1 default=${2:-} secret=${3:-false}
  printf '%s' "$label" >&2
  [[ -z "$default" ]] || printf ' [%s]' "$default" >&2
  printf ': ' >&2
  if [[ "$secret" == true && -t 0 ]]; then
    IFS= read -rs answer || fail 'Setup cancelled; no configuration was saved.'
    printf '\n' >&2
  else
    IFS= read -r answer || fail 'Setup cancelled; no configuration was saved.'
  fi
  answer=${answer:-$default}
  # URI apostrophes/backslashes must be percent-encoded. This also keeps dotenv
  # values single-line and literal, including passwords containing dollar signs.
  [[ "$answer" != *"'"* && "$answer" != *\\* && "$answer" != *$'\r'* ]] ||
    fail 'Use percent-encoded apostrophes/backslashes in URLs; carriage returns are not allowed.'
}

marker='# Spool installation generated by scripts/install.sh'
if [[ -e "$env_file" || -L "$env_file" ]]; then
  [[ -f "$env_file" && ! -L "$env_file" ]] || fail 'The configuration must be a regular file, not a symlink.'
  [[ "$(head -n 1 "$env_file")" == "$marker" ]] ||
    fail "Refusing to overwrite $env_file. Use --env-file with a new path for guided setup."
  chmod 600 "$env_file"
  echo "Reusing $env_file; credentials and service choices are preserved."
else
  command -v openssl >/dev/null || fail 'OpenSSL is required to generate installation secrets.'
  echo 'Spool self-hosted setup'
  echo 'Use the Redis host and database index your Asynq workers use.'
  echo 'Inside Docker, localhost refers to the Spool container. Secret URLs are hidden while you type.'
  ask 'Asynq Redis URL' '' true
  redis_url=$answer
  [[ "$redis_url" =~ ^(redis|rediss|redis-sentinel)://[^/]+ ]] ||
    fail 'Enter a redis://, rediss://, or redis-sentinel:// URL with a host.'

  ask 'PostgreSQL: bundled or external' bundled
  database_mode=$answer
  case "$database_mode" in
    bundled) base=compose.production.redis.yaml; database_url='' ;;
    external)
      base=compose.production.external.yaml
      ask 'PostgreSQL URL (existing database)' '' true
      database_url=$answer
      [[ "$database_url" =~ ^postgres(ql)?://[^/]+/[^?]+ ]] || fail 'Enter a PostgreSQL URL including the database name.' ;;
    *) fail 'Choose bundled or external for PostgreSQL.' ;;
  esac
  ask 'Prometheus: bundled or external' bundled
  metrics_mode=$answer
  case "$metrics_mode" in
    bundled) prometheus_url=http://prometheus:9090 ;;
    external)
      ask 'Prometheus URL (must scrape Spool)' '' true
      prometheus_url=${answer%/}
      [[ "$prometheus_url" =~ ^https?://[^/]+ ]] || fail 'Enter an http:// or https:// Prometheus URL.' ;;
    *) fail 'Choose bundled or external for Prometheus.' ;;
  esac
  if [[ "$browser_setup" == false ]]; then
  ask 'Administrator username' admin
  admin_user=$answer
  [[ "$admin_user" =~ ^[a-zA-Z0-9_.@-]+$ ]] || fail 'Use letters, digits, underscores, dots, @ or hyphens for the username.'
  else
    admin_user=''
  fi
  ask 'Local host port' 8080
  port=$answer
  if [[ ! "$port" =~ ^[1-9][0-9]{0,4}$ ]] || ((port > 65535)); then
    fail 'Choose a port between 1 and 65535.'
  fi
  ask 'Console URL (localhost HTTP or your HTTPS proxy)' "http://localhost:$port"
  console_url=${answer%/}
  case "$console_url" in
    "http://localhost:$port"|"http://127.0.0.1:$port") secure_cookie=false ;;
    https://*)
      [[ "$console_url" =~ ^https://[a-zA-Z0-9.-]+(:[0-9]+)?$ ]] || fail 'Enter an HTTPS origin without a path.'
      secure_cookie=true ;;
    *) fail 'Use localhost HTTP or an HTTPS origin. Remote HTTP is not supported.' ;;
  esac

  organization_name='My organization'
  if [[ "$browser_setup" == false ]]; then
    ask 'Organization name' 'My organization'
    organization_name=$answer
    ((${#organization_name} <= 80)) || fail 'Organization name must be at most 80 characters.'
  fi
  files="$root/$base"
  [[ "$metrics_mode" != bundled ]] || files+=":$root/compose.production.prometheus.yaml"
  files+=":$root/compose.production.host.yaml"
  [[ "$files" != *"'"* && "$files" != *\\* && "$files" != *$'\n'* ]] || fail 'The checkout path contains unsupported characters.'
  admin_password=$(openssl rand -hex 24)
  [[ "$browser_setup" == false ]] || admin_password=''
  metrics_token=$(openssl rand -hex 32)
  data_key=$(openssl rand -hex 32)
  setup_token=$(openssl rand -hex 32)
  session_key=$(openssl rand -hex 32)
  postgres_password=$(openssl rand -hex 32)
  # noclobber prevents concurrent installers from replacing existing credentials.
  (
    set -o noclobber
    cat > "$env_file" <<EOF
$marker
# Compose dotenv file: do not source it or pass it to docker run --env-file.
# Keep this file and the Compose project name stable across upgrades.
COMPOSE_FILE='$files'
COMPOSE_PATH_SEPARATOR=':'
COMPOSE_PROJECT_NAME='spool-production'
REDIS_URL='$redis_url'
DATABASE_URL='$database_url'
POSTGRES_PASSWORD='$postgres_password'
PROMETHEUS_URL='$prometheus_url'
SPOOL_ENV='production'
SPOOL_MULTI_ORG='true'
SPOOL_ORGANIZATION_NAME='$organization_name'
SPOOL_DATA_KEY='$data_key'
SPOOL_METRICS_TOKEN='$metrics_token'
SPOOL_SETUP_TOKEN='$setup_token'
SPOOL_INSTANCE_NAME=''
SPOOL_SUPPORT_URL=''
SPOOL_METRICS_JOB='spool'
SPOOL_ADMIN_USER='$admin_user'
SPOOL_ADMIN_PASSWORD='$admin_password'
SPOOL_SESSION_KEY='$session_key'
SPOOL_VIEWER_USER=''
SPOOL_VIEWER_PASSWORD=''
SPOOL_READ_ONLY='false'
SPOOL_SECURE_COOKIE='$secure_cookie'
SPOOL_HOST_PORT='$port'
SPOOL_INSTALL_URL='$console_url'
EOF
  ) || fail 'Could not save configuration; an existing file was not overwritten.'
  echo "Saved private configuration to $env_file (permissions 600)."
fi

compose config --quiet || fail "Configuration validation failed. Correct $env_file and rerun; secrets were preserved."
printf 'Manage this installation with: docker compose --env-file %q <command>\n' "$env_file"
echo 'Use ps for status, logs for diagnostics, and stop to stop services while keeping data.'
echo "Accounts and setup tokens are in $env_file. Keep SPOOL_DATA_KEY stable and backed up with PostgreSQL."
if [[ "$configure_only" == true ]]; then
  echo 'Configuration validated. Rerun without --configure-only to build and start.'
  exit 0
fi
docker info >/dev/null 2>&1 || fail 'Docker is not running or accessible. Start Docker and rerun; configuration is saved.'
echo 'Building and starting Spool. Waiting up to 180 seconds after the build for service readiness...'
compose up -d --build --wait --wait-timeout 180 ||
  fail 'Startup failed. Check compose logs for Redis reachability, database credentials or an occupied port. Rerun after correcting the issue; data and secrets are preserved.'
if compose config --services | grep -qx prometheus; then
  echo 'Verifying that bundled Prometheus is collecting Spool metrics...'
  scraped=false
  for ((attempt = 0; attempt < 15; attempt++)); do
    if compose exec -T prometheus sh -c 'wget -T 5 -qO- http://127.0.0.1:9090/api/v1/targets | grep -q '\''"health":"up"'\''' ; then
      scraped=true
      break
    fi
    sleep 2
  done
  [[ "$scraped" == true ]] || fail 'Spool is running, but Prometheus cannot scrape it. Check compose logs prometheus and rerun.'
else
  # Expand the saved URL inside the container, rather than on the host.
  # shellcheck disable=SC2016
  compose exec -T app sh -c 'wget -T 10 -q -O /dev/null "${PROMETHEUS_URL%/}/api/v1/query?query=up" 2>/dev/null' ||
    fail 'Spool is running, but external Prometheus is unreachable. Check PROMETHEUS_URL, network access and authentication, then rerun.'
  echo 'External Prometheus: configure its scraper to reach the private /metrics endpoint of this installation.'
fi
console_url=$(sed -n "s/^SPOOL_INSTALL_URL='\([^']*\)'$/\1/p" "$env_file")
echo "Spool is ready. Open $console_url and sign in with the credentials in $env_file, or complete browser setup with the saved setup token."
if [[ "$console_url" == https://* ]]; then
  echo 'Route your HTTPS proxy to the saved loopback port, preserve Host, allow SSE, and block public /metrics.'
fi
